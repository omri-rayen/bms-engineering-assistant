function r = new_result(suite, id, name, requirement)
% Empty test-result skeleton. Tests fill it as they run.
r = struct( ...
    'suite',         suite, ...
    'id',            id, ...
    'name',          name, ...
    'requirement',   requirement, ...
    'status',        "skipped", ...    % pass | fail | error | skipped
    'duration_s',    0, ...
    'error',         "", ...
    'checks',        struct('name',{},'status',{},'detail',{},'value',{},'expected',{}), ...
    'metrics',       struct(), ...
    'signals_plot',  "");              % set by val.scenario_plot
end
